# Writes the bin/ scripts of bundle.app. Arguments: the ruby to run them
# with, the GEM_HOME holding the bundle, the Gemfile to pin Bundler to, the
# groups the bundle was built without (colon separated), the directory to
# write into, then the executable names.
#
# Each script sets the three things Bundler needs to run frozen out of the
# store and then does what `bundle exec <exe>` would.
require "rubygems"

ruby, gem_home, gemfile, without, bin_dir, *exes = ARGV

Gem.paths = { "GEM_HOME" => gem_home, "GEM_PATH" => gem_home }
owner = {}
Gem::Specification.each do |spec|
  spec.executables.each { |exe| owner[exe] ||= spec.name }
end

exes.each do |exe|
  gem_name = owner[exe]
  abort "gemlock: no gem in this bundle provides an executable named '#{exe}'. Known: #{owner.keys.sort.join(", ")}" unless gem_name

  File.write(File.join(bin_dir, exe), <<~RUBY)
    #!#{ruby}
    # Generated by gemlock. Runs the `#{exe}` executable of the #{gem_name} gem
    # against the bundle it was built with.
    ENV["BUNDLE_GEMFILE"] = #{gemfile.dump}
    ENV["BUNDLE_FROZEN"] = "1"
    ENV["BUNDLE_WITHOUT"] = #{without.dump}
    ENV["BUNDLE_VERSION"] = "system"
    ENV.delete("BUNDLE_PATH")
    Gem.paths = { "GEM_HOME" => #{gem_home.dump}, "GEM_PATH" => #{gem_home.dump} }
    require "bundler/setup"
    load Gem.bin_path(#{gem_name.dump}, #{exe.dump})
  RUBY
  File.chmod(0o755, File.join(bin_dir, exe))
end
